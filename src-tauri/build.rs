//! The IPC allow-list. Every command must be listed in COMMANDS: Tauri generates an
//! `allow-<command>` permission for each, and this script writes the capability granting
//! exactly those plus CORE_PERMISSIONS. Anything not listed is rejected at the IPC boundary.

const COMMANDS: &[&str] = &[
    "device_info",
    "scan",
    "get_settings",
    "save_settings",
    "save_app_edit",
    "save_custom_app",
    "delete_custom_app",
    "measure",
    "list_dir",
    "known_folders",
    "volumes",
    "engines_available",
    "preflight",
    "build_snapshot",
    "cancel_build",
    "discard_partial",
    "list_profiles",
    "save_profile",
    "delete_profile",
    "list_snapshots",
    "open_snapshot",
    "verify_snapshot",
    "delete_snapshot",
    "restore_plan",
    "restore_execute",
    "cancel_restore",
    "unlock_summary",
    "find_receivers",
    "send_snapshot",
    "receive_snapshot",
    "answer_offer",
    "cancel_transfer",
    "app_info",
    "system_info",
    "recent_restores",
    "check_update",
    "download_update",
    "cancel_update",
    "install_update",
];

/// Core and plugin permissions the webview needs. No shell, fs or http access.
const CORE_PERMISSIONS: &[&str] = &["core:event:default", "dialog:allow-open"];

fn main() {
    let permissions: Vec<String> = CORE_PERMISSIONS
        .iter()
        .map(|p| p.to_string())
        .chain(
            COMMANDS
                .iter()
                .map(|c| format!("allow-{}", c.replace('_', "-"))),
        )
        .collect();
    let capability = serde_json::json!({
        "$schema": "../gen/schemas/desktop-schema.json",
        "identifier": "main",
        "description": "Generated by build.rs from COMMANDS. Do not edit.",
        "windows": ["main"],
        "permissions": permissions,
    });
    let text = serde_json::to_string_pretty(&capability).expect("serialize capability") + "\n";
    let path = "capabilities/main.json";
    if std::fs::read_to_string(path).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(path, text).expect("write capability");
    }
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(COMMANDS)),
    )
    .expect("failed to run tauri-build");
}
